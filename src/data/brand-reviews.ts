export interface ExternalReviewLink {
  id: 'google' | 'x' | 'naver' | 'jp_web';
  labelKo: string;
  labelJa: string;
  url: string;
}

export function buildExternalReviewLinks(place: PlaceItem, lang: Lang): ExternalReviewLink[] {
  const brandJaShort = place.brandJa.split(/[ (（]/)[0];
  const branchKo = place.nameKo;
  const addrHead = place.addressKo.split(',')[0];
  const jaQuery = `${brandJaShort} ${place.nameJa.split(' ').slice(1).join(' ')} 口コミ OR レポ`.trim();

  return [
    {
      id: 'google',
      labelKo: 'Google 지도 실후기',
      labelJa: 'Googleマップ口コミ',
      url: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${branchKo} ${addrHead}`)}`
    },
    {
      id: 'x',
      labelKo: 'X(트위터) 일본인 레포',
      labelJa: 'X (旧Twitter) リアルレポ',
      url: `https://x.com/search?q=${encodeURIComponent(`${brandJaShort} 韓国 皮膚科`)}&f=live`
    },
    {
      id: 'naver',
      labelKo: '네이버 블로그 실후기',
      labelJa: 'NAVERブログ現地レポ',
      url: `https://search.naver.com/search.naver?where=blog&query=${encodeURIComponent(`${branchKo} 후기`)}`
    },
    {
      id: 'jp_web',
      labelKo: lang === 'ko' ? 'TRIBEAU·Note 일본 후기' : 'TRIBEAU・Note 体験記',
      labelJa: 'TRIBEAU・Note 体験記',
      url: `https://www.google.com/search?q=${encodeURIComponent(`${jaQuery} (site:tribeau.jp OR site:konest.com OR site:note.com OR site:ameblo.jp)`)}`
    }
  ];
}
